//! Q1: high-level `Event` timestamps are SDL nanosecond ticks and equal the raw
//! `SDL_Event` timestamps read via `sdl3-sys`. No sleeps; only ordering checks
//! against SDL's own clock (rule 5).

use sdl_timestamp::{peek_raw_events, raw_timestamp_ns, raw_type, ticks_ns, timestamp_ns};
use sdl3::event::Event;
use sdl3::joystick::{JoystickType, VirtualJoystickDescription};
use sdl3::sys::events::{SDL_EVENT_JOYSTICK_BUTTON_DOWN, SDL_EVENT_QUIT, SDL_Event};

fn peek_ts(raw_type_id: u32) -> Option<u64> {
    let mut buf = [SDL_Event::default(); 64];
    let n = peek_raw_events(&mut buf);
    buf[..n]
        .iter()
        .find(|e| raw_type(e) == raw_type_id)
        .map(raw_timestamp_ns)
}

/// Drain the queue completely. Stopping a `poll_iter()` early leaves SDL3's
/// poll sentinel queued, which makes the *next* poll loop end immediately.
fn drain(pump: &mut sdl3::EventPump) -> Vec<Event> {
    pump.poll_iter().collect()
}

fn main() {
    sdl3::hint::set("SDL_VIDEO_DRIVER", "dummy");
    let sdl = sdl3::init().expect("SDL_Init");
    let events = sdl.event().expect("events subsystem");
    let joystick = sdl.joystick().expect("joystick subsystem");
    let mut pump = sdl.event_pump().expect("event pump");
    drain(&mut pump);

    // Path A: an event pushed with timestamp 0 is stamped by SDL_PushEvent.
    let t0 = ticks_ns();
    events
        .push_event(Event::Quit { timestamp: 0 })
        .expect("push");
    let t1 = ticks_ns();
    let raw = peek_ts(SDL_EVENT_QUIT.0).expect("raw quit event in queue");
    let hl = drain(&mut pump)
        .into_iter()
        .find(|e| matches!(e, Event::Quit { .. }))
        .map(|e| timestamp_ns(&e))
        .expect("high-level quit event");
    println!("[sdl_timestamp] pushed Quit: t0={t0} ts={hl} raw={raw} t1={t1}");
    assert_eq!(hl, raw, "high-level and raw timestamps must match");
    assert!(
        t0 <= hl && hl <= t1,
        "timestamp must be on the SDL_GetTicksNS clock"
    );
    // Sanity: SDL has been up for > 1 µs, so a millisecond value would fail the bound.
    assert!(t0 > 1_000, "tick clock should be in ns");

    // Path B: a real input event generated by a (virtual) device.
    let desc = VirtualJoystickDescription::new()
        .name("ts-probe")
        .joystick_type(JoystickType::Gamepad)
        .with_button(sdl3::gamepad::Button::South);
    let conn = joystick
        .attach_virtual_joystick(desc)
        .expect("virtual joystick");
    let js = joystick.open(conn.id()).expect("open");
    drain(&mut pump);
    js.set_virtual_button(0, true).expect("press");
    let t0 = ticks_ns();
    joystick.update();
    let t1 = ticks_ns();
    let raw = peek_ts(SDL_EVENT_JOYSTICK_BUTTON_DOWN.0).expect("raw button event in queue");
    let hl = drain(&mut pump)
        .into_iter()
        .find(|e| matches!(e, Event::JoyButtonDown { .. }))
        .map(|e| timestamp_ns(&e))
        .expect("high-level JoyButtonDown");
    println!("[sdl_timestamp] JoyButtonDown: t0={t0} ts={hl} raw={raw} t1={t1}");
    assert_eq!(hl, raw);
    assert!(t0 <= hl && hl <= t1);
    drop(js);
    drop(conn);
    println!(
        "[sdl_timestamp] RESULT: sdl3::event::Event exposes SDL ns timestamps (get_timestamp())"
    );
}
