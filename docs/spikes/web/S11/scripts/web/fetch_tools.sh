#!/bin/sh
# Fetch and verify the web build tools for this build host (S11 portable rewrite of S9's
# get_binaryen.sh + the cargo-install steps; proposed scripts/web/fetch_tools.sh, W20).
#
# usage: fetch_tools.sh [--tools DIR] [--lock FILE] [--platform KEY] [--print] [--node]
#                       [--no-cargo] [--no-smoke]
#   --tools DIR     install root (default: $KHZ_WEB_TOOLS, else <repo>/target/web-tools)
#   --lock FILE     pin file (default: tools.lock next to this script)
#   --platform KEY  linux-x86_64 | darwin-arm64 | darwin-x86_64 (default: detected from uname)
#   --print         print the pins selected for the platform and exit (no network)
#   --node          also fetch the pinned Node (otherwise Node 22 must already be on PATH)
#   --no-cargo      skip the `cargo install` tools (wasm-bindgen-cli, wasm-tools)
#   --no-smoke      do not run the fetched binaries (`--version` checks); needed when --platform
#                   names another OS than this one (tests on Linux of the macOS pins)
# env: KHZ_WEB_MIRROR=<dir or URL prefix>: fetch archives by file name from there instead of
#      their upstream URL (CI cache, offline tests); the sha256 pin is checked either way.
#
# Archives are fetched with curl (never a browser), so no com.apple.quarantine attribute is
# set; if one is present anyway (archive copied in by hand), it is removed after verification.
# Writes <tools>/tools.env (sourced by build_web.sh). Exit 0 = every selected tool verified.
set -eu
here=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd -P)
. "$here/lib.sh"

tools=${KHZ_WEB_TOOLS:-}
lock=$here/tools.lock
platform=""
mode=fetch
want_node=0
want_cargo=1
smoke=1
while [ $# -gt 0 ]; do
  case $1 in
    --tools) tools=$2; shift 2 ;;
    --lock) lock=$2; shift 2 ;;
    --platform) platform=$2; shift 2 ;;
    --print) mode=print; shift ;;
    --node) want_node=1; shift ;;
    --no-cargo) want_cargo=0; shift ;;
    --no-smoke) smoke=0; shift ;;
    -h | --help) sed -n '2,20p' "$0"; exit 0 ;;
    *) khz_die "unknown argument: $1" 2 ;;
  esac
done
[ -f "$lock" ] || khz_die "pin file not found: $lock"
if [ -z "$platform" ]; then
  platform=$(khz_platform) || exit 3
fi
case $platform in
  linux-x86_64 | darwin-arm64 | darwin-x86_64) ;;
  *) khz_die "unknown platform key: $platform" 2 ;;
esac
[ -n "$tools" ] || tools=$(khz_abs_dir "$here/../..")/target/web-tools

# Selected pin lines: tool kind version sha256 bytes topdir url (one per line).
pins() {
  awk -v p="$platform" -v node="$want_node" -v cargo="$want_cargo" '
    /^[[:space:]]*#/ || NF == 0 { next }
    ($2 == p || $2 == "any") {
      if ($1 == "node" && node != 1) next
      if ($3 == "cargo" && cargo != 1) next
      print $1, $3, $4, $5, $6, $7, $8
    }' "$lock"
}

if [ "$mode" = print ]; then
  echo "platform $platform"
  pins
  exit 0
fi

mkdir -p "$tools/dl" "$tools/$platform"
tools=$(khz_abs_dir "$tools")
env_file=$tools/tools.env
tmp_env=$tools/.tools.env.$$
: > "$tmp_env"
echo "# generated by fetch_tools.sh for $platform; sourced by build_web.sh" >> "$tmp_env"
echo "KHZ_WEB_PLATFORM='$platform'" >> "$tmp_env"

fetch_archive() { # tool version sha bytes topdir url
  f_tool=$1; f_ver=$2; f_sha=$3; f_bytes=$4; f_top=$5; f_url=$6
  f_dest=$tools/$platform/$f_top
  f_stamp=$f_dest.sha256
  if [ -d "$f_dest" ] && [ -f "$f_stamp" ] && [ "$(cat "$f_stamp")" = "$f_sha" ]; then
    echo "ok   $f_tool $f_ver ($platform) already verified: $f_dest"
    return 0
  fi
  f_name=$(basename "$f_url")
  f_arc=$tools/dl/$f_name
  if [ ! -f "$f_arc" ]; then
    f_src=$f_url
    [ -n "${KHZ_WEB_MIRROR:-}" ] && f_src=${KHZ_WEB_MIRROR%/}/$f_name
    echo "get  $f_tool $f_ver ($platform) from $f_src"
    case $f_src in
      http://* | https://* | file://*)
        curl -fsSL --retry 3 --connect-timeout 30 --max-time 1800 -o "$f_arc.part" "$f_src" ||
          { rm -f "$f_arc.part"; khz_die "download failed: $f_src"; } ;;
      *) cp "$f_src" "$f_arc.part" || khz_die "copy failed: $f_src" ;;
    esac
    mv "$f_arc.part" "$f_arc"
  fi
  f_got=$(khz_sha256 "$f_arc")
  f_size=$(khz_size "$f_arc")
  if [ "$f_got" != "$f_sha" ] || { [ "$f_bytes" != - ] && [ "$f_size" != "$f_bytes" ]; }; then
    rm -f "$f_arc"
    khz_die "checksum mismatch for $f_name: got sha256 $f_got ($f_size bytes), pinned $f_sha ($f_bytes bytes); archive deleted"
  fi
  echo "sha256 OK $f_name $f_got"
  f_stage=$(mktemp -d "$tools/.stage.XXXXXX")
  if ! tar -xzf "$f_arc" -C "$f_stage"; then rm -rf "$f_stage"; khz_die "extract failed: $f_arc"; fi
  [ -d "$f_stage/$f_top" ] || { rm -rf "$f_stage"; khz_die "archive $f_name has no top directory $f_top"; }
  rm -rf "$f_dest"
  mv "$f_stage/$f_top" "$f_dest"
  rm -rf "$f_stage"
  # A browser download carries com.apple.quarantine; curl does not. Drop it if present.
  if [ "$(uname -s 2>/dev/null)" = Darwin ] && command -v xattr >/dev/null 2>&1; then
    xattr -dr com.apple.quarantine "$f_dest" 2>/dev/null || true
  fi
  printf '%s\n' "$f_sha" > "$f_stamp"
  [ "${KHZ_KEEP_DL:-0}" = 1 ] || rm -f "$f_arc"
  echo "ok   $f_tool $f_ver ($platform) -> $f_dest"
}

cargo_tool() { # crate version
  c_crate=$1; c_ver=$2
  case $c_crate in wasm-bindgen-cli) c_bin=wasm-bindgen ;; *) c_bin=$c_crate ;; esac
  c_root=$tools/cargo
  if [ -x "$c_root/bin/$c_bin" ] && "$c_root/bin/$c_bin" --version 2>/dev/null | grep -q " $c_ver\$"; then
    echo "ok   $c_crate $c_ver already installed: $c_root/bin/$c_bin"
    return 0
  fi
  command -v cargo >/dev/null 2>&1 || khz_die "cargo not found: install rustup and the pinned toolchain first"
  echo "cargo install --locked $c_crate $c_ver"
  cargo install --locked --root "$c_root" "$c_crate" --version "$c_ver" || khz_die "cargo install $c_crate $c_ver failed"
}

pins > "$tools/.pins.$$"
while read -r p_tool p_kind p_ver p_sha p_bytes p_top p_url; do
  case $p_kind in
    archive) fetch_archive "$p_tool" "$p_ver" "$p_sha" "$p_bytes" "$p_top" "$p_url" ;;
    cargo) cargo_tool "$p_tool" "$p_ver" ;;
    *) khz_die "unknown kind $p_kind in $lock" ;;
  esac
  case $p_tool in
    wasi-sdk) echo "KHZ_WASI_SDK='$tools/$platform/$p_top'" >> "$tmp_env" ;;
    binaryen) echo "KHZ_BINARYEN='$tools/$platform/$p_top'" >> "$tmp_env" ;;
    node) echo "KHZ_NODE='$tools/$platform/$p_top'" >> "$tmp_env" ;;
  esac
done < "$tools/.pins.$$"
rm -f "$tools/.pins.$$"
[ "$want_cargo" = 1 ] && echo "KHZ_CARGO_TOOLS='$tools/cargo'" >> "$tmp_env"
mv "$tmp_env" "$env_file"

if [ "$smoke" = 1 ]; then
  # Run every fetched binary once: catches a wrong architecture, a missing bundled dylib, an
  # unsigned arm64 binary (killed by the kernel) or a Gatekeeper block before the build does.
  # shellcheck source=/dev/null
  . "$env_file"
  check() { # label expected-substring command...
    c_label=$1; c_want=$2; shift 2
    c_out=$("$@" 2>&1 | head -1) || true
    case $c_out in
      *"$c_want"*) echo "smoke OK   $c_label: $c_out" ;;
      *) khz_die "smoke FAIL $c_label: expected '$c_want', got '$c_out' (run: $*)" ;;
    esac
  }
  check clang "clang version 22.1.0-wasi-sdk" "$KHZ_WASI_SDK/bin/clang" --version
  # shellcheck disable=SC2016  # $1 expands in the inner sh
  check llvm-ar "LLVM version 22.1.0-wasi-sdk" sh -c '"$1" --version | grep "LLVM version"' sh "$KHZ_WASI_SDK/bin/llvm-ar"
  check wasm-opt "wasm-opt version 132" "$KHZ_BINARYEN/bin/wasm-opt" --version
  if [ "$want_cargo" = 1 ]; then
    check wasm-bindgen "wasm-bindgen 0.2.130" "$KHZ_CARGO_TOOLS/bin/wasm-bindgen" --version
    check wasm-tools "wasm-tools 1.263.0" "$KHZ_CARGO_TOOLS/bin/wasm-tools" --version
  fi
  if [ "$want_node" = 1 ]; then check node "v22.23.5" "$KHZ_NODE/bin/node" --version; fi
fi
echo "tools for $platform verified; environment in $env_file"
