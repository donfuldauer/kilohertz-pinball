#[test]
fn wall_errors() {
    let wall = |points: Vec<[f32; 2]>, closed: bool| Wall {
        points,
        closed,
        material: Material::Wood,
    };
    let mut lay = empty();
    lay.walls = vec![
        wall(vec![[0.0, 0.0], [10.0, 0.0]], false),
        wall(vec![[0.0, 0.0]], false),
    ];
    let e = err(&lay);
    assert_eq!(e.element, "walls[1]");
    assert!(e.message.contains("at least 2"), "{e}");
    lay.walls[1] = wall(vec![[0.0, 0.0], [0.0, 0.0]], false);
    assert!(err(&lay).message.contains("repeats"));
    lay.walls[1] = wall(vec![[0.0, 0.0], [9.0e3, 0.0]], false);
    assert!(err(&lay).message.contains("within"));
    lay.walls[1] = wall(
        vec![[0.0, 0.0], [10.0, 10.0], [10.0, 0.0], [0.0, 10.0]],
        true,
    );
    let e = err(&lay);
    assert_eq!(e.element, "walls[1]");
    assert!(e.message.contains("crosses"), "{e}");
    lay.walls[1] = wall(vec![[0.0, 0.0]; 2000], false);
    assert!(err(&lay).message.contains("more than"));
    // The same polyline open is fine; closed with a repeated first point too.
    lay.walls[1] = wall(
        vec![[0.0, 0.0], [10.0, 10.0], [10.0, 0.0], [0.0, 10.0]],
        false,
    );
    generate(&lay, &base()).unwrap();
    lay.walls[1] = wall(
        vec![[0.0, 0.0], [10.0, 0.0], [10.0, 10.0], [0.0, 0.0]],
        true,
    );
    generate(&lay, &base()).unwrap();
}

