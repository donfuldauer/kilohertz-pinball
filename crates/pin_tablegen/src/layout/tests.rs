/// Rail samples follow the roll as well as the curvature: a straight 19 mm
/// wireform rolling through 90° keeps each interval's roll change below the
/// ~7.4° that holds a rail chord within the facet tolerance.
#[test]
fn wire_samples_bound_roll_change() {
    let pts = [Vec3::ZERO, Vec3::new(0.0, 0.1, 0.0)];
    let centre = CubicSpline::interpolate(&pts).unwrap();
    let wf = Wireform::new(centre.clone(), &[0.0, 90.0], 0.019, Vec3::Z).unwrap();
    let ts = wire_samples(&wf);
    let limit = 2.0 * libm::acos(1.0 - mesh::FACET_TOLERANCE_M / 0.0095);
    assert!(limit.to_degrees() < 7.5 && limit.to_degrees() > 7.3);
    for w in ts.windows(2) {
        let d = f64::from((wf.roll_rad(w[1]) - wf.roll_rad(w[0])).abs());
        assert!(d <= limit, "roll step {}° over {:?}", d.to_degrees(), w);
    }
    // Without roll the straight rail needs only the minimum sampling.
    let flat = Wireform::new(centre, &[0.0, 0.0], 0.019, Vec3::Z).unwrap();
    assert_eq!(wire_samples(&flat).len(), 3);
}

/// The entry zone needs a start direction with a plan component.
#[test]
fn entry_zone_needs_a_plan_direction() {
    let p0 = [0.0, 0.0, 0.0];
    for t in [Vec3::ZERO, Vec3::NAN, Vec3::new(f32::INFINITY, 0.0, 0.0)] {
        let e = entry::entry_zone(p0, t, 40.0).unwrap_err();
        assert!(e.contains("no start direction"), "{t:?}: {e}");
    }
    let e = entry::entry_zone(p0, Vec3::new(1.0e-9, 0.0, -1.0), 40.0).unwrap_err();
    assert!(e.contains("starts vertically"), "{e}");
    // Level along +x: the square ahead of the start.
    let z = entry::entry_zone([10.0, 20.0, 0.0], Vec3::X * 0.3, 40.0).unwrap();
    assert_eq!(z.min, [10.0, 0.0, 0.0]);
    assert_eq!(z.max, [50.0, 40.0, 20.0]);
    assert!(entry::overlaps(&z, &z));
    let touching = AabbDef {
        min: [50.0, 0.0, 0.0],
        max: [60.0, 1.0, 1.0],
    };
    assert!(entry::overlaps(&z, &touching));
    let apart = AabbDef {
        min: [50.001, 0.0, 0.0],
        max: [60.0, 1.0, 1.0],
    };
    assert!(!entry::overlaps(&z, &apart));
}

/// The JSON chunk length of a generated glb.
fn json_len(glb: &[u8]) -> u64 {
    u64::from(u32::from_le_bytes([glb[12], glb[13], glb[14], glb[15]]))
}

/// The number after `would be ` in a budget message.
fn would_be(message: &str) -> u64 {
    let rest = message.split("would be ").nth(1).unwrap();
    rest.split(' ').next().unwrap().parse().unwrap()
}

/// SPEC §4 4.3 (#137, test A): 12,000 inserts whose lamp id is 1,500
/// characters long carry 18,000,000 bytes of lamp extras, over the
/// loader's 16 MiB glb JSON budget (with 12,001 nodes, under the 16,384
/// node cap): the error names `inserts`, the JSON size and the node count.
#[test]
fn json_budget_names_inserts() {
    let lamp = "l".repeat(1_500);
    let mut b = base();
    let mut def = b.lamps[0].clone();
    def.id = lamp.clone();
    def.number = 3;
    b.lamps.push(def);
    let mut lay = empty();
    lay.inserts = (0..12_000)
        .map(|i| Insert {
            lamp: lamp.clone(),
            position: [20.0 + (i % 100) as f32 * 4.0, 20.0 + (i / 100) as f32 * 4.0],
            shape: InsertShape::Rect,
            size: 3.0,
        })
        .collect();
    assert!(12_000 * 1_500 > GltfLimits::default().max_json_bytes);
    assert!(12_001 < GltfLimits::default().max_meshes);
    let e = generate(&lay, &b).unwrap_err();
    assert_eq!(e.element, "inserts", "{e}");
    assert!(e.message.contains("playfield.glb JSON"), "{e}");
    assert!(e.message.contains("(12000 inserts nodes)"), "{e}");
    assert!(
        e.message
            .contains(&format!("more than the {}", 16u64 << 20)),
        "{e}"
    );
    assert!(would_be(&e.message) > 18_000_000, "{e}");
}

/// A walls-heavy layout: `walls` walls and three posts.
fn walls_heavy(walls: usize) -> LayoutManifest {
    let mut lay = empty();
    lay.walls = (0..walls)
        .map(|i| Wall {
            points: vec![[10.0 + i as f32, 10.0], [10.0 + i as f32, 60.0]],
            closed: false,
            material: Material::Wood,
        })
        .collect();
    lay.posts = (0..3)
        .map(|i| Post {
            position: [300.0, 200.0 + 50.0 * i as f32],
            radius: 5.0,
            rubber: false,
        })
        .collect();
    lay
}

/// SPEC §4 4.3 (#137, test B): an oversized walls-heavy layout names
/// `walls` (the kind with the most nodes) and its count; exactly at the
/// budget it generates.
#[test]
fn json_budget_names_walls() {
    let lay = walls_heavy(200);
    let g = generate(&lay, &base()).unwrap();
    let json = json_len(&g.glb);
    let limits = |max_json_bytes| GltfLimits {
        max_json_bytes,
        ..GltfLimits::default()
    };
    // At the budget: fine, and the same output as `generate`.
    assert_eq!(
        generate_with_limits(&lay, &base(), limits(json)).unwrap(),
        g
    );
    let e = generate_with_limits(&lay, &base(), limits(json - 1)).unwrap_err();
    assert_eq!(e.element, "walls", "{e}");
    assert!(e.message.contains("playfield.glb JSON"), "{e}");
    assert!(e.message.contains("(200 walls nodes)"), "{e}");
    assert_eq!(would_be(&e.message), json, "{e}");
}

