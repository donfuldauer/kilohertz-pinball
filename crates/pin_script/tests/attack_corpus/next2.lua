function on_tick()
 assert(select('#', 1, 2, 3) == 3) assert(rawlen({1,2}) == 2) assert(rawequal(pinball, pinball)) assert(next(pinball.sw) == nil)
 assert(rawget(pinball, "pulse_coil") == nil)
 local ok = pcall(function() pinball.sw.x = 1 end) assert(not ok)
 local ok = pcall(rawset, pinball.sw, "x", 1) assert(not ok)
 local ok = pcall(rawset, pinball, "x", 1) assert(not ok)
 local ok = pcall(table.insert, pinball.sw, 1) assert(not ok, "table.insert")
 local ok = pcall(setmetatable, pinball.sw, {}) assert(not ok)
 local ok = pcall(setmetatable, pinball, {}) assert(not ok)
 assert(utf8.char(228) == "ä") assert(utf8.len("\xff") == nil)
 assert(os == nil)
 assert(math.random(1,1) == 1)
 local ok = pcall(math.random, 1, 2, 3) assert(not ok)
 local ok = pcall(math.random, 2, 1) assert(not ok)
 local ok = pcall(math.random, 1.5) assert(not ok)
 local ok = pcall(math.random, "x") assert(not ok)
 local x = math.random(0) assert(math.type(x) == "integer")
 local f = math.random() assert(f >= 0 and f < 1)
 assert(math.random(math.mininteger, math.maxinteger))
 assert(math.random(3.0) <= 3)
 pinball.pulse_coil(2, 2)
end
