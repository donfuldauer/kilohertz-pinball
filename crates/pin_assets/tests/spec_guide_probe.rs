fn with_spline(replacement: &str, t: &str) -> String {
    let start = t.find("[[splines]]").unwrap();
    let end = t.find("[[layer_transitions]]").unwrap();
    format!("{}{}\n\n{}", &t[..start], replacement, &t[end..])
}
fn probe(name: &str, table: &str, pts: &str) {
    let t = with_spline(&format!("[[splines]]\nid = \"g\"\nkind = \"guide\"\nlayer = 0\npoints = {pts}"), table);
    let vfs = vfs_from(&bundle_with(&t, BACKGLASS_TOML));
    match load_table(&vfs) {
        Ok(t) => { println!("== {name}: OK"); for w in t.warnings.iter().filter(|w| w.path.starts_with("splines")) { println!("   W {w}"); } }
        Err(e) => println!("== {name}: ERR {e}"),
    }
}
